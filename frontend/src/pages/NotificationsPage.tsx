import { Bell, CheckCheck, CheckCircle2, CircleAlert } from 'lucide-react';
import { useEffect, useState } from 'react';

import { Button } from '../components/ui/Button';
import { Card } from '../components/ui/Card';
import { useAuth } from '../contexts/AuthContext';
import { api, type NotificationPayload } from '../services/api';

export function NotificationsPage() {
  const { token } = useAuth();
  const [items, setItems] = useState<NotificationPayload[]>([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);

  const loadNotifications = async () => {
    if (!token) return;
    try {
      setLoading(true);
      const result = await api.getNotifications(token);
      setItems(result.items);
      setError(null);
    } catch (err) {
      setError(err instanceof Error ? err.message : 'Unable to load notifications.');
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    void loadNotifications();
  }, [token]);

  const onMarkRead = async (notificationId: number) => {
    if (!token) return;
    try {
      await api.markNotificationRead(token, notificationId);
      setItems((current) => current.map((item) => (item.id === notificationId ? { ...item, is_read: true } : item)));
    } catch {
      setError('Unable to update the notification status.');
    }
  };

  const onMarkAllRead = async () => {
    if (!token) return;
    try {
      await api.markAllNotificationsRead(token);
      setItems((current) => current.map((item) => ({ ...item, is_read: true })));
    } catch {
      setError('Unable to mark all notifications as read.');
    }
  };

  if (loading) {
    return <div className="rounded-xl border border-slate-200 bg-white p-6 text-slate-600">Loading notifications…</div>;
  }

  if (error) {
    return <div className="rounded-xl border border-rose-200 bg-rose-50 p-6 text-rose-700">{error}</div>;
  }

  return (
    <div className="space-y-6">
      <div className="flex flex-col gap-3 sm:flex-row sm:items-center sm:justify-between">
        <div>
          <p className="text-sm font-medium uppercase tracking-[0.2em] text-slate-500">Operations</p>
          <h1 className="mt-1 text-3xl font-semibold text-slate-900">Notifications</h1>
        </div>
        <Button variant="secondary" onClick={() => void onMarkAllRead()}>
          <CheckCheck size={16} className="mr-2" />
          Mark all as read
        </Button>
      </div>

      <Card>
        {items.length === 0 ? (
          <div className="flex flex-col items-center justify-center gap-3 py-8 text-center text-slate-600">
            <Bell size={28} className="text-slate-400" />
            <div className="text-lg font-medium">No notifications yet</div>
            <div className="text-sm text-slate-500">Operational alerts will appear here when they are generated by the backend.</div>
          </div>
        ) : (
          <div className="space-y-3">
            {items.map((item) => (
              <div key={item.id} className={`rounded-xl border p-4 ${item.is_read ? 'border-slate-200 bg-slate-50' : 'border-amber-200 bg-amber-50'}`}>
                <div className="flex flex-col gap-3 sm:flex-row sm:items-start sm:justify-between">
                  <div className="flex items-start gap-3">
                    <div className={`mt-0.5 rounded-full p-2 ${item.severity === 'CRITICAL' ? 'bg-rose-100 text-rose-600' : item.severity === 'HIGH' ? 'bg-amber-100 text-amber-600' : 'bg-sky-100 text-sky-600'}`}>
                      {item.severity === 'CRITICAL' || item.severity === 'HIGH' ? <CircleAlert size={16} /> : <CheckCircle2 size={16} />}
                    </div>
                    <div>
                      <div className="text-sm font-semibold uppercase tracking-wide text-slate-700">{item.notification_type}</div>
                      <div className="mt-1 text-lg font-semibold text-slate-900">{item.title}</div>
                      <div className="mt-1 text-sm text-slate-600">{item.message}</div>
                      <div className="mt-2 text-xs text-slate-500">{new Date(item.created_at).toLocaleString()} </div>
                    </div>
                  </div>

                  {!item.is_read && (
                    <Button variant="secondary" size="sm" onClick={() => void onMarkRead(item.id)}>
                      Mark read
                    </Button>
                  )}
                </div>
              </div>
            ))}
          </div>
        )}
      </Card>
    </div>
  );
}
